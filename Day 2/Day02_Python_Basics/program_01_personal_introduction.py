# Question: Part G - Program 1: Personal Introduction
# Problem statement: Ask name, age and city. Print a simple introduction.
# Input: Name (string), Age (integer), City (string)
# Processing / formula: Combine the inputs into one sentence.
# Output: A greeting sentence with name, age, and city.
# ==============================================================================

name = input("Enter your name: ")
age = int(input("Enter your age: "))
city = input("Enter your city: ")

print("Hello, my name is", name, "I am", age, "years old and I live in", city)

